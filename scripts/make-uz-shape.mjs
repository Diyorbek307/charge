// Extracts Uzbekistan's outline from Natural Earth (world-atlas) into a small
// module the landing's 3D map imports, so the full atlas never ships.
// Run: node scripts/make-uz-shape.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { feature } from 'topojson-client';

const topo = JSON.parse(readFileSync('node_modules/world-atlas/countries-50m.json', 'utf8'));
const uz = feature(topo, topo.objects.countries).features.find(f => f.id === '860');
if (!uz) throw new Error('Uzbekistan (ISO 860) not found');

const polys = uz.geometry.type === 'Polygon' ? [uz.geometry.coordinates] : uz.geometry.coordinates;
// Keep outer rings only; round to 3 decimals (~100 m) — plenty for a hero map.
const rings = polys.map(p => p[0].map(([lng, lat]) => [+lng.toFixed(3), +lat.toFixed(3)]));
rings.sort((a, b) => b.length - a.length);

const out = `// Generated by scripts/make-uz-shape.mjs from Natural Earth 1:50m (public domain).
// [lng, lat] outer rings, largest first.
export const UZ_RINGS: [number, number][][] = ${JSON.stringify(rings)};
`;
writeFileSync('src/landing/uzShape.ts', out);
console.log('rings:', rings.map(r => r.length), 'bytes:', out.length);
